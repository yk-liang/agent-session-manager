import { copyFileSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const root = fileURLToPath(new URL('../', import.meta.url));
const source = path.join(root, 'src/assets/brand/app-icon.svg');
let dark = readFileSync(source, 'utf8');

// 深色版只替换底座渐变；轮廓、S 折带和高光始终来自同一份 SVG。
const palettes = {
  tile: '<stop stop-color="#303B55"/><stop offset=".48" stop-color="#222B40"/><stop offset="1" stop-color="#151C2E"/>',
  tileLight: '<stop stop-color="#A4C5FF" stop-opacity=".14"/><stop offset="1" stop-color="#A4C5FF" stop-opacity="0"/>',
  tileEdge: '<stop stop-color="#9CB3E2" stop-opacity=".58"/><stop offset=".52" stop-color="#768BB9" stop-opacity=".15"/><stop offset="1" stop-color="#0C1224" stop-opacity=".65"/>',
};
for (const [id, stops] of Object.entries(palettes)) {
  const gradient = new RegExp(`(<(?:linear|radial)Gradient id="${id}"[^>]*>)[\\s\\S]*?(</(?:linear|radial)Gradient>)`);
  if (!gradient.test(dark)) throw new Error(`Missing icon gradient: ${id}`);
  dark = dark.replace(gradient, (_, start, end) => `${start}\n      ${stops}\n    ${end}`);
}
writeFileSync(path.join(root, 'src/assets/brand/app-icon-dark.svg'), `<!-- Generated by npm run icons; edit app-icon.svg and scripts/generate-icons.mjs. -->\n${dark}`);

// Tauri 同时生成移动端资源；本仓库只复制桌面产物，临时文件不进入版本管理。
const staging = mkdtempSync(path.join(tmpdir(), 'asm-icons-'));
try {
  execFileSync(process.execPath, [path.join(root, 'node_modules/@tauri-apps/cli/tauri.js'), 'icon', source, '--output', staging], { cwd: root, stdio: 'inherit' });
  const icons = readdirSync(staging).filter(file => /\.(png|ico|icns)$/.test(file));
  for (const file of icons) copyFileSync(path.join(staging, file), path.join(root, 'src-tauri/icons', file));
  console.log(`Generated ${icons.length} desktop icons and the dark SVG variant.`);
} finally {
  rmSync(staging, { recursive: true, force: true });
}
