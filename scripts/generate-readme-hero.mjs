import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// README 顶部图：六个 Agent 摆在程序坞里，会话数据向上汇入应用图标；另生成中英文下载按钮。
// 图标与应用内 AgentIcon 同源，增删 Agent 时只需修改 AGENTS 后重新运行 npm run docs:hero。
const root = fileURLToPath(new URL('../', import.meta.url));
const read = file => readFileSync(path.join(root, file), 'utf8');
const lobe = name => read(`node_modules/@lobehub/icons-static-svg/icons/${name}.svg`);
const GENERATED = '<!-- Generated by npm run docs:hero; edit scripts/generate-readme-hero.mjs. -->\n';

// 数据流从 Agent 品牌色出发；黑白图标没有品牌色，用两档灰区分。
const AGENTS = [
  { icon: lobe('qoder-color'), color: '#2ADB5C' },
  { icon: lobe('claudecode-color'), color: '#D97757' },
  { icon: lobe('codex-color'), color: '#9A8CFF' },
  { icon: lobe('opencode'), color: '#3B4458' },
  { icon: lobe('pi'), color: '#7A859C' },
  { icon: read('src/assets/agents/antigravity.svg'), color: '#3186FF' },
];
const APP_ICON = read('src/assets/brand/app-icon.svg');
// 与应用图标 S 折带相同的渐变，数据流汇入应用时过渡到这组颜色。
const RIBBON = ['#62DAF0', '#419CF0', '#5C6BE2', '#6540CB'];
const INK = '#1D2433';
const FONT = `-apple-system, BlinkMacSystemFont, 'Segoe UI', 'PingFang SC', 'Microsoft YaHei', sans-serif`;

const round = n => Math.round(n * 10) / 10;
const channels = color => color.match(/\w\w/g).map(v => parseInt(v, 16));
const mix = (a, b, t) => `#${channels(a).map((v, i) => Math.round(v + (channels(b)[i] - v) * t).toString(16).padStart(2, '0')).join('')}`;
function ribbonAt(t) {
  const span = t * (RIBBON.length - 1), i = Math.min(RIBBON.length - 2, Math.floor(span));
  return mix(RIBBON[i], RIBBON[i + 1], span - i);
}

let instance = 0;
// 把源 SVG 内联为嵌套 <svg>；内部 id 加前缀，避免多个图标的渐变、蒙版互相覆盖。
function inline(source, x, y, size) {
  const rootTag = source.match(/<svg[^>]*>/)[0];
  const attr = name => rootTag.match(new RegExp(`\\s${name}="([^"]+)"`))?.[1];
  let inner = source.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
    .replace(/<title>[\s\S]*?<\/title>/g, '').replace(/<!--[\s\S]*?-->/g, '').replace(/\n\s*/g, '');
  const prefix = `i${instance++}-`;
  for (const [, id] of inner.matchAll(/\bid="([^"]+)"/g)) {
    const escaped = id.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    inner = inner.replace(new RegExp(`id="${escaped}"`, 'g'), `id="${prefix}${id}"`)
      .replace(new RegExp(`url\\(#${escaped}\\)`, 'g'), `url(#${prefix}${id})`)
      .replace(new RegExp(`href="#${escaped}"`, 'g'), `href="#${prefix}${id}"`);
  }
  const fillRule = attr('fill-rule');
  return `<svg x="${round(x)}" y="${round(y)}" width="${size}" height="${size}" viewBox="${attr('viewBox')}" fill="${attr('fill') ?? 'black'}" color="${INK}"${fillRule ? ` fill-rule="${fillRule}"` : ''}>${inner}</svg>`;
}

function hero() {
  const W = 1280, H = 440;
  const app = { x: 640, y: 122, size: 172 };
  const tile = 68, gap = 22, pad = 24;
  const dock = { w: AGENTS.length * tile + (AGENTS.length - 1) * gap + pad * 2, y: 312, h: tile + 30 };
  dock.x = (W - dock.w) / 2;
  const tileY = dock.y + 11 + tile / 2;
  const defs = [
    `<linearGradient id="bg" x1="0" y1="0" x2="0" y2="${H}" gradientUnits="userSpaceOnUse"><stop stop-color="#F3F7FF"/><stop offset="1" stop-color="#D8E3FA"/></linearGradient>`,
    `<radialGradient id="halo" cx="${app.x}" cy="150" r="380" gradientUnits="userSpaceOnUse"><stop stop-color="#A9C4FF" stop-opacity=".45"/><stop offset="1" stop-color="#A9C4FF" stop-opacity="0"/></radialGradient>`,
    `<clipPath id="frame"><rect width="${W}" height="${H}" rx="28"/></clipPath>`,
    '<filter id="soft" x="-50%" y="-50%" width="200%" height="200%"><feGaussianBlur stdDeviation="6"/></filter>',
    // 浅色图标放在浅色背景上，靠投影与背景分开。
    '<filter id="lift" x="-30%" y="-30%" width="160%" height="170%"><feDropShadow dy="10" stdDeviation="14" flood-color="#1B2A5E" flood-opacity=".22"/></filter>',
  ];
  const streams = [], tiles = [];
  AGENTS.forEach((agent, k) => {
    const x = dock.x + pad + tile / 2 + k * (tile + gap), xe = app.x + (k - 2.5) * 13;
    const y0 = tileY - tile / 2 - 4, ye = app.y + 60;
    const d = `M${round(x)} ${y0}C${round(x)} ${y0 - 70} ${round(xe)} ${ye + 70} ${round(xe)} ${ye}`;
    defs.push(`<linearGradient id="s${k}" gradientUnits="userSpaceOnUse" x1="0" y1="${y0}" x2="0" y2="${ye}"><stop offset="0" stop-color="${agent.color}"/><stop offset=".42" stop-color="${agent.color}"/><stop offset="1" stop-color="${ribbonAt(k / (AGENTS.length - 1))}"/></linearGradient>`);
    streams.push(`<path class="track" d="${d}" stroke="url(#s${k})"/><path class="flow" d="${d}" stroke="url(#s${k})" style="animation-delay:-${round(k * 0.37)}s"/>`);
    const icon = Math.round(tile * 0.56);
    tiles.push(`<rect x="${round(x - tile / 2 + .5)}" y="${round(tileY - tile / 2 + .5)}" width="${tile - 1}" height="${tile - 1}" rx="16" fill="#FFFFFF" stroke="#E1E7F3"/>${inline(agent.icon, x - icon / 2, tileY - icon / 2, icon)}<circle cx="${round(x)}" cy="${dock.y + dock.h - 7}" r="2.5" fill="#5B6478"/>`);
  });
  const style = '<style>.track{fill:none;stroke-linecap:round;stroke-width:3;opacity:.5}.flow{fill:none;stroke-linecap:round;stroke-width:5;stroke-dasharray:.01 24;animation:flow 1.8s linear infinite}@keyframes flow{to{stroke-dashoffset:-24}}@media (prefers-reduced-motion:reduce){.flow{animation:none}}</style>';
  return `${GENERATED}<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}" fill="none"><title>Agent Session Manager</title>${style}<defs>${defs.join('')}</defs>`
    + `<g clip-path="url(#frame)"><rect width="${W}" height="${H}" fill="url(#bg)"/><rect width="${W}" height="${H}" fill="url(#halo)"/>${streams.join('')}`
    + `<rect x="${round(dock.x)}" y="${dock.y + 6}" width="${dock.w}" height="${dock.h}" rx="26" fill="#1B2A5E" opacity=".10" filter="url(#soft)"/>`
    + `<rect x="${round(dock.x + .5)}" y="${dock.y + .5}" width="${dock.w - 1}" height="${dock.h - 1}" rx="26" fill="#FFFFFF" fill-opacity=".58" stroke="#FFFFFF" stroke-opacity=".95"/>${tiles.join('')}`
    + `<g filter="url(#lift)">${inline(APP_ICON, app.x - app.size / 2, app.y - app.size / 2, app.size)}</g></g></svg>\n`;
}

// 下载按钮：文字宽度按 macOS 系统字体测得，textLength 保证其他系统字体下也不溢出。
function downloadButton(label, textWidth) {
  const h = 44, padLeft = 18, icon = 18, gap = 8, padRight = 20;
  const w = Math.ceil(padLeft + icon + gap + textWidth + padRight);
  const download = ['M12 15V3', 'M21 15v4a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2v-4', 'm7 10 5 5 5-5'];
  return `${GENERATED}<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}" fill="none"><title>${label}</title>`
    + `<defs><linearGradient id="fill" x1="0" y1="0" x2="${w}" y2="0" gradientUnits="userSpaceOnUse"><stop stop-color="${RIBBON[1]}"/><stop offset="1" stop-color="${RIBBON[2]}"/></linearGradient></defs>`
    + `<rect width="${w}" height="${h}" rx="12" fill="url(#fill)"/><rect x=".5" y=".5" width="${w - 1}" height="${h - 1}" rx="11.5" stroke="#FFFFFF" stroke-opacity=".22"/>`
    + `<g transform="translate(${padLeft} ${(h - icon) / 2}) scale(${icon / 24})" stroke="#FFFFFF" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round">${download.map(d => `<path d="${d}"/>`).join('')}</g>`
    + `<text x="${padLeft + icon + gap}" y="${h / 2}" dominant-baseline="central" textLength="${textWidth}" lengthAdjust="spacingAndGlyphs" fill="#FFFFFF" font-family="${FONT}" font-size="15" font-weight="600">${label}</text></svg>\n`;
}

const outputs = {
  'docs/images/hero.svg': hero(),
  'docs/images/download.svg': downloadButton('Download for macOS', 151),
  'docs/images/download.zh-CN.svg': downloadButton('下载 macOS 版', 104),
};
for (const [file, content] of Object.entries(outputs)) writeFileSync(path.join(root, file), content);
console.log(`Generated ${Object.keys(outputs).join(', ')}.`);
